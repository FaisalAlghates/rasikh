// Generates CSS variables, a Tailwind v4 @theme block and a Flutter ThemeExtension from tokens.json.
// Fails the build if any WCAG contrast pair is below its required ratio.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(join(root, 'tokens.json'), 'utf8'));

const resolve = (v) => (t.color[v] ?? v).toUpperCase();

// ---------- contrast ----------
const lin = (c) => ((c /= 255) <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const lum = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  return 0.2126 * lin(n >> 16) + 0.7152 * lin((n >> 8) & 255) + 0.0722 * lin(n & 255);
};
const ratio = (a, b) => {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

let failed = 0;
const report = [];
for (const mode of ['light', 'dark']) {
  for (const [fg, bg, min] of t.contrastPairs) {
    const r = ratio(resolve(t.theme[mode][fg]), resolve(t.theme[mode][bg]));
    const ok = r >= min;
    if (!ok) failed++;
    report.push(
      `${ok ? 'PASS' : 'FAIL'} ${mode.padEnd(5)} ${fg} on ${bg}: ${r.toFixed(2)} (min ${min})`,
    );
  }
}
console.log(report.join('\n'));
if (failed) {
  console.error(`\n${failed} contrast pair(s) failed.`);
  process.exit(1);
}

// ---------- outputs ----------
const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
const out = join(root, 'dist');
mkdirSync(out, { recursive: true });

const themeVars = (mode) =>
  Object.entries(t.theme[mode])
    .map(([k, v]) => `  --rk-${kebab(k)}: ${resolve(v)};`)
    .join('\n');

const staticVars = [
  ...Object.entries(t.color).map(([k, v]) => `  --rk-c-${kebab(k)}: ${v};`),
  ...Object.entries(t.fontSize).map(([k, v]) => `  --rk-fs-${k}: ${v / 16}rem;`),
  ...Object.entries(t.lineHeight).map(([k, v]) => `  --rk-lh-${k}: ${v};`),
  ...t.space.map((v, i) => `  --rk-space-${i}: ${v / 16}rem;`),
  ...Object.entries(t.radius).map(([k, v]) => `  --rk-radius-${k}: ${v}px;`),
  `  --rk-ease: cubic-bezier(${t.motion.easing.join(', ')});`,
  `  --rk-dur-fast: ${t.motion.fast}ms;`,
  `  --rk-dur-base: ${t.motion.base}ms;`,
  `  --rk-dur-slow: ${t.motion.slow}ms;`,
  `  --rk-border-alpha: ${t.borderAlpha};`,
].join('\n');

const css = `/* GENERATED by scripts/build.mjs — do not edit. */
:root {
${staticVars}
${themeVars('light')}
  color-scheme: light;
}
[data-theme='light'] {
${themeVars('light')}
  color-scheme: light;
}
[data-theme='dark'] {
${themeVars('dark')}
  color-scheme: dark;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
${themeVars('dark').replace(/^/gm, '  ')}
    color-scheme: dark;
  }
}
@media (prefers-reduced-motion: reduce) {
  :root {
    --rk-dur-fast: 0.01ms;
    --rk-dur-base: 0.01ms;
    --rk-dur-slow: 0.01ms;
  }
}
`;
writeFileSync(join(out, 'tokens.css'), css);

const roleNames = Object.keys(t.theme.light);
const twTheme = `/* GENERATED — Tailwind v4 theme bound to the CSS variables. */
@theme inline {
${roleNames.map((k) => `  --color-${kebab(k)}: var(--rk-${kebab(k)});`).join('\n')}
  --color-clay: var(--rk-c-clay);
  --color-clay-light: var(--rk-c-clay-light);
  --color-night: var(--rk-c-night);
  --color-charcoal: var(--rk-c-charcoal);
  --color-sand: var(--rk-c-sand);
  --color-stone: var(--rk-c-stone);
  --radius-sm: var(--rk-radius-sm);
  --radius-md: var(--rk-radius-md);
  --radius-lg: var(--rk-radius-lg);
  --radius-xl: var(--rk-radius-xl);
${Object.keys(t.fontSize)
  .map((k) => `  --text-${k}: var(--rk-fs-${k});`)
  .join('\n')}
  --ease-rk: var(--rk-ease);
  --font-display: var(--font-fraunces), var(--font-reem-kufi), serif;
  --font-sans: var(--font-plex-sans), var(--font-plex-arabic), system-ui, sans-serif;
}
`;
writeFileSync(join(out, 'tailwind-theme.css'), twTheme);

// Dart
const dartHex = (hex) => `Color(0xFF${hex.slice(1)})`;
const camel = (s) => s;
const dart = `// GENERATED by packages/design-tokens/scripts/build.mjs — do not edit.
import 'package:flutter/material.dart';

@immutable
class RasikhTokens extends ThemeExtension<RasikhTokens> {
  const RasikhTokens({
${roleNames.map((k) => `    required this.${camel(k)},`).join('\n')}
  });

${roleNames.map((k) => `  final Color ${camel(k)};`).join('\n')}

  static const light = RasikhTokens(
${roleNames.map((k) => `    ${camel(k)}: ${dartHex(resolve(t.theme.light[k]))},`).join('\n')}
  );

  static const dark = RasikhTokens(
${roleNames.map((k) => `    ${camel(k)}: ${dartHex(resolve(t.theme.dark[k]))},`).join('\n')}
  );

  static const Curve ease = Cubic(${t.motion.easing.join(', ')});
  static const Duration fast = Duration(milliseconds: ${t.motion.fast});
  static const Duration base = Duration(milliseconds: ${t.motion.base});
  static const Duration slow = Duration(milliseconds: ${t.motion.slow});
  static const Duration camera = Duration(milliseconds: ${t.motion.camera});

  static const double radiusSm = ${t.radius.sm};
  static const double radiusMd = ${t.radius.md};
  static const double radiusLg = ${t.radius.lg};
  static const double radiusXl = ${t.radius.xl};

  static const String arDisplay = '${t.font.arDisplay}';
  static const String arBody = '${t.font.arBody}';
  static const String latDisplay = '${t.font.latDisplay}';
  static const String latBody = '${t.font.latBody}';

  @override
  RasikhTokens copyWith({
${roleNames.map((k) => `    Color? ${camel(k)},`).join('\n')}
  }) =>
      RasikhTokens(
${roleNames.map((k) => `        ${camel(k)}: ${camel(k)} ?? this.${camel(k)},`).join('\n')}
      );

  @override
  RasikhTokens lerp(ThemeExtension<RasikhTokens>? other, double t) {
    if (other is! RasikhTokens) return this;
    return RasikhTokens(
${roleNames.map((k) => `      ${camel(k)}: Color.lerp(${camel(k)}, other.${camel(k)}, t)!,`).join('\n')}
    );
  }
}
`;
writeFileSync(join(out, 'rasikh_tokens.g.dart'), dart);
// Keep the Flutter app in sync with the tokens.
const mobileTheme = join(root, '..', '..', 'apps', 'mobile', 'lib', 'theme');
if (existsSync(join(root, '..', '..', 'apps', 'mobile', 'lib'))) {
  mkdirSync(mobileTheme, { recursive: true });
  writeFileSync(join(mobileTheme, 'rasikh_tokens.g.dart'), dart);
}

writeFileSync(join(out, 'contrast-report.txt'), report.join('\n') + '\n');
console.log('\nTokens built.');
